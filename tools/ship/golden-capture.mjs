#!/usr/bin/env node
// Produces stamped goldens from oracle runs, and decides what may be committed.
//
//   node tools/ship/golden-capture.mjs --kind text
//   node tools/ship/golden-capture.mjs --kind e2e --report tmp/e2e-full.json
//
// PLAN.md §11's principle: expected results only come from the oracle. This
// script runs the oracle, writes the golden, writes the oracle's own log, and
// then stamps the golden through `golden-stamp.mjs --write` (the only way a
// stamp can be made).
//
// # What may be committed
//
// X's text and pixels are X's property (PLAN.md §11: the captures live in a
// private store, "the repository holds only a lockfile of hashes"). So:
//
// | Golden | Contents | Committed? |
// |---|---|---|
// | `tests/golden/text.json` | our *synthetic* fuzz/coverage strings and Chrome's line boxes for them | **yes** — the text is generated by us, the numbers are facts |
// | `tests/golden/e2e.json` | per-post verdicts, height deltas, line counts, pixel ratios and SHA-256 of the line text; no text, no pixels | **yes** — counts, numbers and hashes |
// | `tests/golden/raster/*.png` | Chrome screenshots of real posts | **no** — private store only |
// | corpus-derived text goldens | X's post text | **no** — private store only |
//
// `--no-corpus` is therefore not an optimisation: it is what makes the text
// golden committable.
//
// The e2e digest is a *trend* gate, not a pixel gate: it records today's
// agreement so a change that makes the renderer worse against real posts is
// visible in the diff, without shipping anyone's posts.

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const args = process.argv.slice(2);
const opt = (name, dflt) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 && args[i + 1] ? args[i + 1] : dflt;
};
const KIND = opt("kind", "text");
const GOLDEN_DIR = join(ROOT, "tests", "golden");
const LOG_DIR = join(ROOT, "tmp", "oracle-logs");

/** The Chrome the oracle actually used, so the stamp is attributable. */
async function chromeVersion() {
  const { launch } = await import("../oracle/browser.mjs");
  const browser = await launch();
  const version = browser.version();
  await browser.close();
  return version;
}

function stamp(golden, log) {
  const out = execFileSync(
    "node",
    [join(ROOT, "tools", "ship", "golden-stamp.mjs"), "--write", "--golden", golden, "--oracle-log", log],
    { cwd: ROOT, encoding: "utf8" },
  );
  process.stdout.write(out);
}

async function captureText() {
  const out = join(GOLDEN_DIR, "text.json");
  // `--no-corpus`: synthetic strings only (fuzz + coverage sets), so the golden
  // carries no post text from X.
  const stdout = execFileSync(
    "node",
    [
      join(ROOT, "tools", "oracle", "text-parity.mjs"),
      "--no-corpus",
      // `space` and the fuzz generator pass today; the `styled` and `emoji`
      // coverage sets still disagree with Chrome on line breaks (reported to
      // the text stream), so they are deliberately not in the committed golden.
      // A golden records agreement we have, not agreement we want.
      "--fuzz", "150",
      "--set", "space",
      "--n", "60",
      "--seed", "20261110",
      "--save", out,
    ],
    { cwd: ROOT, encoding: "utf8", maxBuffer: 1 << 28 },
  );
  const summary = JSON.parse(stdout.slice(stdout.lastIndexOf("{", stdout.indexOf('"samples"'))));
  const log = { chrome: await chromeVersion(), cases: summary.samples, script: "tools/oracle/text-parity.mjs", sets: ["fuzz", "space"] };
  const logPath = join(LOG_DIR, "text.json");
  writeJson(logPath, log);
  stamp(out, logPath);
  console.log(`goldens: text — ${summary.samples} cases, ${summary.layouts} layouts, ${summary.lineBreakMismatches} line mismatches`);
  if (summary.lineBreakMismatches > 0 || summary.heightMismatches > 0) {
    console.error("goldens: the oracle found disagreements; the golden records them, so the parity gate will fail until they are fixed");
    process.exit(1);
  }
}

async function captureE2e() {
  const reportPath = opt("report", join(ROOT, "tmp", "e2e-full.json"));
  if (!existsSync(reportPath)) {
    console.error(`goldens: no e2e report at ${reportPath}; run node tools/ship/e2e.mjs --json ${reportPath} first`);
    process.exit(2);
  }
  const report = JSON.parse(readFileSync(reportPath, "utf8"));
  const cases = report.results
    .filter((r) => !["skip", "error"].includes(r.verdict))
    .map((r) => ({
      // No text, no pixels: a hash of the line text and the numbers that were
      // compared. Enough to detect drift, nothing of X's to publish.
      case: `${r.file}:${r.id}`,
      verdict: r.verdict,
      heightDelta: r.height?.delta ?? null,
      lines: r.lines ? { chrome: r.lines.chrome, xeet: r.lines.xeet, sameContent: r.lines.sameContent ?? null } : null,
      lineHash: createHash("sha256").update(String(r.lines?.firstDiff?.chrome ?? "") + "|" + String(r.lines?.firstDiff?.xeet ?? "")).digest("hex").slice(0, 16),
      pixelRatio: r.pixels?.ratio ?? null,
    }));
  const summary = report.summary ?? {};
  const golden = {
    $comment:
      "End-to-end agreement against the captured x.com pages (PLAN.md §10 layer 2). Counts, deltas and hashes only: the posts' text and the screenshots are X's and stay in the private store. Produced by tools/ship/golden-capture.mjs --kind e2e.",
    upstream: report.upstream,
    viewport: report.viewport,
    dpr: report.dpr,
    totals: { compared: cases.length, ...summary },
    cases,
  };
  const out = join(GOLDEN_DIR, "e2e.json");
  writeJson(out, golden);
  const log = { chrome: await chromeVersion(), cases: cases.length, script: "tools/ship/e2e.mjs", upstream: { appVersion: report.upstream } };
  const logPath = join(LOG_DIR, "e2e.json");
  writeJson(logPath, log);
  stamp(out, logPath);
  console.log(`goldens: e2e — ${cases.length} cases recorded (digest ${report.digest ?? "?"})`);
}

function writeJson(path, value) {
  execFileSync("mkdir", ["-p", dirname(path)]);
  writeFileSync(path, JSON.stringify(value, null, 2) + "\n");
}

if (KIND === "text") await captureText();
else if (KIND === "e2e") await captureE2e();
else {
  console.error(`goldens: unknown --kind ${KIND}; expected text or e2e`);
  process.exit(2);
}
