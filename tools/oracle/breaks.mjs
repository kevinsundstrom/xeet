#!/usr/bin/env node
// Derives Chrome's line-break behavior for ASCII pairs by asking Chrome.
//
// Chrome does not consult UAX #14 when both characters around a position are
// ASCII; it uses its own pair table. This script recovers that table by laying
// out every pair in a zero-width box (so every opportunity is taken) and
// writes it as Rust source.
//
//   node tools/oracle/breaks.mjs            # writes crates/xeet-core/src/blink_ascii.rs
import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { launch, newPage, setContentAs, ROOT } from "./browser.mjs";

const FIRST = 0x21, LAST = 0x7e, N = LAST - FIRST + 1;
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

// Each probe is "a" + x + y + "a". Letters on both sides are neutral context.
let body = "";
for (let x = FIRST; x <= LAST; x++) {
  for (let y = FIRST; y <= LAST; y++) {
    body += `<p>${esc("a" + String.fromCharCode(x, y) + "a")}</p>`;
  }
}
const html = `<!DOCTYPE html><html><head><meta charset="utf-8"><style>
p{margin:0;width:0;white-space:pre-wrap;overflow-wrap:normal;word-break:normal;font:15px/20px monospace}
</style></head><body>${body}</body></html>`;

const browser = await launch();
const { page } = await newPage(browser, { width: 400, height: 400, dpr: 1 });
await setContentAs(page, html, "/i/breaks");
// For each probe: is there a line break between character 1 (x) and 2 (y)?
const bits = await page.evaluate(() => {
  const out = [];
  const range = document.createRange();
  for (const p of document.querySelectorAll("p")) {
    const node = p.firstChild;
    const top = (i) => { range.setStart(node, i); range.setEnd(node, i + 1); return range.getClientRects()[0].top; };
    out.push(top(2) > top(1) + 1 ? 1 : 0);
  }
  return out;
});
const version = await browser.version();
await browser.close();

const rows = [];
let allowed = 0;
for (let x = 0; x < N; x++) {
  let v = 0n;
  for (let y = 0; y < N; y++) {
    if (bits[x * N + y]) { v |= 1n << BigInt(y); allowed++; }
  }
  rows.push(`    0x${v.toString(16).padStart(24, "0")}, // ${JSON.stringify(String.fromCharCode(FIRST + x))}`);
}
const src = `//! Chrome's line-break table for ASCII pairs. GENERATED by tools/oracle/breaks.mjs.
//!
//! Derived by laying out every pair in Chrome ${version} in a zero-width box.
//! Row = the character before the position, bit = the character after it,
//! both offset from 0x21. A set bit means Chrome may break between them.
//! ${allowed} of ${N * N} pairs allow a break.

pub const FIRST: u8 = 0x${FIRST.toString(16)};
pub const LAST: u8 = 0x${LAST.toString(16)};

pub static BREAK_AFTER: [u128; ${N}] = [
${rows.join("\n")}
];

/// True if Chrome allows a line break between ASCII characters \`a\` and \`b\`.
#[inline]
pub fn may_break(a: u8, b: u8) -> bool {
    (BREAK_AFTER[(a - FIRST) as usize] >> (b - FIRST)) & 1 == 1
}
`;
await writeFile(join(ROOT, "crates", "xeet-core", "src", "blink_ascii.rs"), src);
console.log(`wrote blink_ascii.rs from Chrome ${version}: ${allowed}/${N * N} pairs allow a break`);
