EMOJI_DATA = os.path.join(VENDOR, "unicode", "emoji-data-17.0.txt")


def emoji_data_ranges(prop: str):
    """The code point ranges of one property in emoji-data.txt, merged."""
    ranges = []
    with open(EMOJI_DATA, "rb") as f:
        for line in f.read().decode("utf-8").splitlines():
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            fields = [x.strip() for x in line.split(";")]
            if len(fields) < 2 or fields[1] != prop:
                continue
            cps = fields[0]
            if ".." in cps:
                lo, hi = cps.split("..")
                ranges.append((int(lo, 16), int(hi, 16)))
            else:
                v = int(cps, 16)
                ranges.append((v, v))
    return merge(ranges)


def gen_unicode_properties():
    h = fnv1a(open(EMOJI_DATA, "rb").read())
    pictographic = emoji_data_ranges("Extended_Pictographic")
    modifiers = emoji_data_ranges("Emoji_Modifier")
    out = [
        HEADER.format(sources="unicode/emoji-data-17.0.txt", hash=h),
        "//! Unicode emoji properties, from Unicode's `emoji-data.txt` 17.0.",
        "//!",
        "//! These are the properties X's shipped client uses in its emoji regex:",
        "//! `\\p{Extended_Pictographic}` and `\\p{EMod}`. (`\\p{Regional_Indicator}` is a",
        "//! single block, U+1F1E6..U+1F1FF, and is written out in `emoji.rs` rather",
        "//! than generated.) The tables were checked against a V8 that reports",
        "//! Unicode 17.0; see `tests/x_client.rs`.",
    ]
    for name, doc, ranges in [
        ("EXTENDED_PICTOGRAPHIC", "`\\p{Extended_Pictographic}`.", pictographic),
        ("EMOJI_MODIFIER", "`\\p{Emoji_Modifier}` (the skin-tone swatches).", modifiers),
    ]:
        out.append("")
        out.append("/// %s" % doc)
        out.append("pub static %s: &[(u32, u32)] = &[" % name)
        row = []
        for lo, hi in ranges:
            row.append("(0x%04X, 0x%04X)" % (lo, hi))
            if len(row) == 4:
                out.append("    " + ", ".join(row) + ",")
                row = []
        if row:
            out.append("    " + ", ".join(row) + ",")
        out.append("];")
    with open(os.path.join(OUT, "emoji_props.rs"), "w") as f:
        f.write("\n".join(out).rstrip() + "\n")
    print(
        "emoji_props.rs: %d pictographic ranges, %d modifier ranges"
        % (len(pictographic), len(modifiers))
    )


def gen_sources():
    """A list of every vendored input and its own hash.

    The crate's tests recompute these, so a table that no longer matches its
    source is a test failure rather than silent drift.
    """
    regexp_dir = os.path.join(VENDOR, "twitter-text", "regexp")
    files = [
        "twitter-text/regexp/" + n
        for n in sorted(os.listdir(regexp_dir))
        if n.endswith(".js")
    ]
    files.append("twitter-text/TwitterTextEmojiRegex.java")
    files.append("twitter-text/configs.js")
    files.append("twitter-text/getCharacterWeight.js")
    files.append("unicode/emoji-data-17.0.txt")
    lines = ["# Generated by tools/gen_tables.py -- do not edit by hand.", "# path<TAB>FNV-1a 64"]
    for name in files:
        with open(os.path.join(VENDOR, name), "rb") as f:
            h = fnv1a(f.read())
        lines.append("%s\t0x%016x" % (name, h))
    with open(os.path.join(VENDOR, "SOURCES.lock"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("SOURCES.lock: %d inputs" % len(files))


