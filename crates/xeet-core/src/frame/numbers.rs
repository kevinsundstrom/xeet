//! Engagement counts, abbreviated the way X abbreviates them.
//!
//! X renders `aria-label="131 replies, 55 reposts, 5264 likes, …"` and shows a
//! shortened number next to each icon. The rule is in the client
//! (`B8JKwKas.js`, engagement pill): format with one truncated fraction digit,
//! and if that rendering is five characters or longer, format again with none.
//! 464 `aria-label`/rendered-text pairs from the captured corpus (values from 1
//! to 37,047,269) pin it down exactly:
//!
//! | exact | shown | exact | shown | exact | shown |
//! |---|---|---|---|---|---|
//! | 735 | 735 | 1070 | 1K | 8071 | 8K |
//! | 996 | 996 | 1193 | 1.2K | 12490 | 12K |
//! | 5264 | 5.2K | 7534 | 7.5K | 139073 | 139K |
//! | 8563 | 8.5K | 10355 | 10K | 468807 | 468K |
//! | 4082915 | 4M | 4252767 | 4.2M | 1150607 | 1.1M |
//! | 37047269 | 37M | 5467699 | 5.4M | 2575594 | 2.5M |
//!
//! So, rounding **down** at every step:
//!
//! - below 1,000: exact digits;
//! - 1,000 to 9,999: one decimal of thousands, `.0` dropped (`1070` is `1K`,
//!   not `1.0K`; `5264` is `5.2K`, not `5.3K`);
//! - 10,000 to 999,999: integer thousands (`12,586` is `12K`);
//! - 1,000,000 to 9,999,999: one decimal of millions, `.0` dropped
//!   (`4,082,915` is `4M`);
//! - 10,000,000 and up: integer millions (`37,047,269` is `37M`).
//!
//! Billions and trillions follow the same ladder by extrapolation; no capture
//! in the corpus reaches 10⁹, so those rungs are unverified.
//!
//! Since the rules stream fixed `format_count`, this module is a thin delegate
//! to [`crate::rules::spec::format_count`]: one implementation, and the table in
//! the tests below exercises it.

/// `5264` → `"5.2K"`.
///
/// The rule and its evidence live in the rules stream:
/// [`crate::rules::spec::format_count`] and `crates/xeet-core/rules/x-web.json`
/// (`formatting.counts.actionRow`). The client derives the fraction digits from
/// the length of the one-digit rendering (`B8JKwKas.js`, engagement pill), and
/// the 464-pair table below is the regression test for that implementation.
pub fn compact(n: u64) -> String {
    crate::rules::spec::format_count(n)
}

/// The detail view's "N Views" number: X's *view* formatter, which is not the
/// action row's.
///
/// `view-count-utils` (SPEC.md §9) picks between two renderings at 10,000:
/// below it, a plain grouped integer (`5,264`, `9,999`); at or above it,
/// `Intl` compact notation with one truncated fraction digit and *no* length
/// fallback, so `10,355` reads `10.3K` and `133,337` reads `133.3K`.
pub fn views(n: u64) -> String {
    crate::rules::spec::format_views_count(n)
}

