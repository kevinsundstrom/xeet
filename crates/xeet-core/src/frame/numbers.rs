    #[test]
    fn views_ladder() {
        // The boundary and both sides of it; `view-count-utils` evidence in
        // SPEC.md §9. Above 10,000 the fraction digit stays even when the text
        // is long, unlike the action row's five-character fallback.
        for (n, want) in [
            (0, "0"),
            (999, "999"),
            (5264, "5,264"),
            (9999, "9,999"),
            (10_000, "10K"),
            (10_355, "10.3K"),
            (12_490, "12.4K"),
            (133_337, "133.3K"),
            (987_654, "987.6K"),
            (1_150_607, "1.1M"),
            (37_047_269, "37M"),
        ] {
            assert_eq!(views(n), want, "views({n})");
            // The action row's rule disagrees above 10,000, by design.
        }
        assert_eq!(compact(10_355), "10K");
        assert_eq!(compact(5264), "5.2K");
    }

    #[test]
    fn boundaries() {
        assert_eq!(compact(0), "0");
        assert_eq!(compact(999), "999");
        assert_eq!(compact(1000), "1K");
        assert_eq!(compact(9999), "9.9K");
        assert_eq!(compact(10_000), "10K");
        assert_eq!(compact(999_999), "999K");
        assert_eq!(compact(1_000_000), "1M");
        assert_eq!(compact(9_999_999), "9.9M");
        assert_eq!(compact(10_000_000), "10M");
    }
